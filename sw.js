// Réseau d'abord, cache en secours. B12 : seules les réponses valides (2xx, même origine) remplacent la copie en cache,
// et la réponse est clonée AVANT d'être rendue à la page (sinon son corps peut déjà être consommé).
self.addEventListener('fetch',event=>{if(event.request.method!=='GET')return;
  event.respondWith(fetch(event.request).then(response=>{if(response.ok&&response.type==='basic'){const copy=response.clone();
  caches.open(CACHE).then(cache=>cache.put(event.request,copy)).catch(()=>{});}return response}).catch(()=>caches.match(event.request).then(response=>response||caches.match('./index.html'))))});
